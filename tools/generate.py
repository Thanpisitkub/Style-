#!/usr/bin/env python3
"""Generate every data file of the mod from the single table tools/styles.json.

Writes, relative to the repository root:
  src/main/resources/data/fiststyle/capabilities/weapons/style_N.json
  src/main/resources/data/fiststyle/capabilities/weapons/types/style_N.json
  src/main/resources/assets/fiststyle/models/item/style_N.json
  src/main/resources/assets/fiststyle/lang/en_us.json
  src/main/resources/assets/fiststyle/textures/item/style_s.png
  src/main/java/dev/fiststyle/StyleStats.java

Usage: python3 tools/generate.py
"""
import json
from pathlib import Path

from PIL import Image

MOD_ID = "fiststyle"
GUARD_ANIMATION = "epicfight:biped/skill/guard_uchigatana"
MOUNT_ANIMATION = "epicfight:biped/combat/sword_mount_attack"
INNATE_SKILL = "epicfight:relentless_combo"
HELD_ITEM_DISPLAY_KEYS = (
    "thirdperson_righthand",
    "thirdperson_lefthand",
    "firstperson_righthand",
    "firstperson_lefthand",
)

# 7 wide x 11 tall letter S; '#' is white.
GLYPH = (
    ".#####.",
    "#.....#",
    "#......",
    "#......",
    "#......",
    ".#####.",
    "......#",
    "......#",
    "......#",
    "#.....#",
    ".#####.",
)
BLACK = (0, 0, 0, 255)
WHITE = (255, 255, 255, 255)


def load_styles(path: Path) -> list:
    return json.loads(Path(path).read_text(encoding="utf-8"))["styles"]


def _impact(n: int) -> float:
    return round(0.5 + 0.15 * (n - 1), 2)


def _living_motion(style: dict, known: set) -> dict:
    prefix = f"wom:biped/living/{style['idle']}"
    motion = {"block": GUARD_ANIMATION, "idle": f"{prefix}_idle"}
    # run/walk/chase are left out when WOM has no such animation for the set
    # (Style 2 has no run), so the game falls back to its default.
    for key, animation in (("run", f"{prefix}_run"), ("walk", f"{prefix}_walk"), ("chase", f"{prefix}_run")):
        if animation in known:
            motion[key] = animation
    return motion


def build_type(style: dict, known: set) -> dict:
    """Weapon type JSON, mirroring effs:hand_combat key for key."""
    n = style["n"]
    required = list(style["combos"]) + [f"wom:biped/living/{style['idle']}_idle"]
    unknown = [animation for animation in required if animation not in known]
    if unknown:
        raise ValueError(f"style {n}: animations not in known_animations.json: {unknown}")
    living = _living_motion(style, known)
    return {
        "category": "sword",
        "hit_particle": "epicfight:entity.hit.blunt",
        "hit_sound": "epicfight:entity.hit.blunt",
        "swing_sound": "epicfight:entity.weapon.whoosh_hard",
        "styles": {
            "cases": [
                {
                    "condition": "epicfight:offhand_category",
                    "predicate": {"category": "sword"},
                    "style": "two_hand",
                }
            ],
            "default": "one_hand",
        },
        "offhand_item_compatible_predicate": {
            "condition": "epicfight:offhand_category",
            "predicate": {"category": "greatsword"},
        },
        "collider": {
            "number": 3,
            "center": [0.0, 0.0, -0.75],
            "size": [0.4, 0.4, 0.8],
        },
        "combos": {
            "one_hand": list(style["combos"]),
            "two_hand": list(style["combos"]),
            "mount": [MOUNT_ANIMATION],
        },
        "innate_skills": {"one_hand": INNATE_SKILL, "two_hand": INNATE_SKILL},
        "livingmotion_modifier": {"one_hand": dict(living), "two_hand": dict(living)},
    }


def build_capability(style: dict) -> dict:
    n = style["n"]
    return {
        "type": f"{MOD_ID}:style_{n}",
        "attributes": {
            "common": {"armor_negation": 0.0, "impact": _impact(n), "max_strikes": 1}
        },
    }


def build_item_model() -> dict:
    return {
        "parent": "item/handheld",
        "textures": {"layer0": f"{MOD_ID}:item/style_s"},
        "display": {key: {"scale": [0, 0, 0]} for key in HELD_ITEM_DISPLAY_KEYS},
    }


def build_lang(styles: list) -> dict:
    lang = {f"item.{MOD_ID}.style_{s['n']}": f"Style {s['n']}" for s in styles}
    lang[f"itemGroup.{MOD_ID}"] = "Style"
    return lang


def build_texture() -> Image.Image:
    image = Image.new("RGBA", (16, 16), BLACK)
    left = (16 - len(GLYPH[0])) // 2
    top = (16 - len(GLYPH)) // 2
    for y, row in enumerate(GLYPH):
        for x, cell in enumerate(row):
            if cell == "#":
                image.putpixel((left + x, top + y), WHITE)
    return image


def build_stats_java(styles: list) -> str:
    damage = ", ".join(repr(float(s["damage"])) for s in styles)
    speed = ", ".join(repr(float(s["speed"])) for s in styles)
    uppercut = ",\n".join(f'        "{s["combos"][3]}"' for s in styles)
    return (
        "// GENERATED by tools/generate.py — do not edit\n"
        "package dev.fiststyle;\n"
        "\n"
        "/** Per-style stats; index = style number - 1. */\n"
        "public final class StyleStats {\n"
        f"    public static final double[] DAMAGE = {{{damage}}};\n"
        f"    public static final double[] SPEED = {{{speed}}};\n"
        "    /** Animation id of the fourth punch (the uppercut) of each style. */\n"
        "    public static final String[] UPPERCUT = {\n"
        f"{uppercut}\n"
        "    };\n"
        "\n"
        "    private StyleStats() {\n"
        "    }\n"
        "}\n"
    )


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def _write_json(path: Path, data: dict) -> None:
    _write_text(path, json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def write_all(root: Path, styles: list, known: set) -> None:
    root = Path(root)
    resources = root / "src/main/resources"
    weapons = resources / "data" / MOD_ID / "capabilities/weapons"
    assets = resources / "assets" / MOD_ID
    model = build_item_model()
    for style in styles:
        n = style["n"]
        _write_json(weapons / f"style_{n}.json", build_capability(style))
        _write_json(weapons / "types" / f"style_{n}.json", build_type(style, known))
        _write_json(assets / "models/item" / f"style_{n}.json", model)
    _write_json(assets / "lang/en_us.json", build_lang(styles))
    texture = assets / "textures/item/style_s.png"
    texture.parent.mkdir(parents=True, exist_ok=True)
    build_texture().save(texture, format="PNG")
    _write_text(root / "src/main/java/dev/fiststyle/StyleStats.java", build_stats_java(styles))


def main() -> None:
    tools = Path(__file__).resolve().parent
    styles = load_styles(tools / "styles.json")
    known = set(json.loads((tools / "known_animations.json").read_text(encoding="utf-8")))
    write_all(tools.parent, styles, known)
    print(f"generated {len(styles)} styles")


if __name__ == "__main__":
    main()
